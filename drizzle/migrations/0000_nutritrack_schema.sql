CREATE TABLE public.profiles (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  display_name text NOT NULL DEFAULT 'Member',
  age smallint NOT NULL DEFAULT 25,
  gender text NOT NULL DEFAULT 'Prefer not to say',
  height_cm numeric(6,2) NOT NULL DEFAULT 170,
  weight_kg numeric(6,2) NOT NULL DEFAULT 70,
  activity_level text NOT NULL DEFAULT 'moderate',
  goal text NOT NULL DEFAULT 'maintain',
  preferences text[] NOT NULL DEFAULT ARRAY[]::text[],
  restrictions text[] NOT NULL DEFAULT ARRAY[]::text[],
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
GRANT SELECT, INSERT, UPDATE, DELETE ON public.profiles TO authenticated;
GRANT ALL ON public.profiles TO service_role;
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Members read their own profile" ON public.profiles FOR SELECT TO authenticated USING (id = auth.uid());
CREATE POLICY "Members create their own profile" ON public.profiles FOR INSERT TO authenticated WITH CHECK (id = auth.uid());
CREATE POLICY "Members update their own profile" ON public.profiles FOR UPDATE TO authenticated USING (id = auth.uid()) WITH CHECK (id = auth.uid());
CREATE POLICY "Members delete their own profile" ON public.profiles FOR DELETE TO authenticated USING (id = auth.uid());

