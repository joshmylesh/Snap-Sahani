CREATE OR REPLACE FUNCTION public.handle_new_nutritrack_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  metadata jsonb := COALESCE(NEW.raw_user_meta_data, '{}'::jsonb);
  parsed_age integer := 25;
  parsed_height numeric := 170;
  parsed_weight numeric := 70;
BEGIN
  IF COALESCE(metadata->>'age', '') ~ '^[0-9]{1,3}$' THEN
    parsed_age := (metadata->>'age')::integer;
  END IF;
  IF parsed_age < 13 OR parsed_age > 110 THEN parsed_age := 25; END IF;
  IF COALESCE(metadata->>'height_cm', '') ~ '^[0-9]{1,3}(\.[0-9]{1,2})?$' THEN
    parsed_height := (metadata->>'height_cm')::numeric;
  END IF;
  IF parsed_height <= 0 OR parsed_height > 300 THEN parsed_height := 170; END IF;
  IF COALESCE(metadata->>'weight_kg', '') ~ '^[0-9]{1,3}(\.[0-9]{1,2})?$' THEN
    parsed_weight := (metadata->>'weight_kg')::numeric;
  END IF;
  IF parsed_weight <= 0 OR parsed_weight > 1000 THEN parsed_weight := 70; END IF;

  INSERT INTO public.profiles (id, display_name, age, gender, height_cm, weight_kg, activity_level, goal)
  VALUES (
    NEW.id,
    COALESCE(NULLIF(metadata->>'name', ''), NULLIF(metadata->>'full_name', ''), split_part(COALESCE(NEW.email, 'Member'), '@', 1)),
    parsed_age,
    CASE WHEN metadata->>'gender' IN ('Female','Male','Non-binary','Prefer not to say') THEN metadata->>'gender' ELSE 'Prefer not to say' END,
    parsed_height,
    parsed_weight,
    CASE WHEN metadata->>'activity_level' IN ('sedentary','light','moderate','active') THEN metadata->>'activity_level' ELSE 'moderate' END,
    CASE WHEN metadata->>'goal' IN ('lose','maintain','gain') THEN metadata->>'goal' ELSE 'maintain' END
  ) ON CONFLICT (id) DO NOTHING;
  INSERT INTO public.goals (user_id) VALUES (NEW.id) ON CONFLICT (user_id) DO NOTHING;
  INSERT INTO public.weight_logs (user_id, weight_kg) VALUES (NEW.id, parsed_weight);
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION public.handle_new_nutritrack_user() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.handle_new_nutritrack_user() TO supabase_auth_admin;
CREATE TRIGGER on_auth_user_created_nutritrack
AFTER INSERT ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.handle_new_nutritrack_user();